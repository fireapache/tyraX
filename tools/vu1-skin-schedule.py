#!/usr/bin/env python3
"""List-schedule the VU1 skinning blend and count its cycles per corner; emit the pass.

An independent cross-check of the cycle figures in docs/animated-models.md ("Skinning on
VU1"). It reads the blend sketch (skin_vu1_blend_sketch.vsm.txt), keeps the joint blocks for
k influences (a line naming joint j is dropped when j >= k), and schedules the operations on
the two VU pipes:

  upper pipe: one FMAC / EFU / ITOF / FTOI operation per cycle
  lower pipe: one load (LQ, ILW) or store (SQ) per cycle, in parallel with the upper pipe

Dependencies are program order: a read waits for the write before it (latency), a write
waits for the reads before it, and a write waits for the write before it. The issue
priority is program order, and a VF value is only defined while the budget (30 usable
registers; vf31 holds the constant 127) has room.

Result latencies (ASSUMPTIONS, not measured here; the docs section says so):
  FMAC, ITOF, FTOI ................... 4 cycles   (the repo's FMAC latency)
  RSQRT (EFU, into Q) ................ 12 cycles
  LQ, ILW (loads) .................... 4 cycles   (--load-latency changes it)

Modes:
  (default)            the table: cycles per corner for k = 1..4, isolated and steady
  --emit PATH          the scheduled body of --copies corners, as assembler lines
  --program PATH       the whole pass as a .vclpp source: header, the corner-pair loop,
                       the body, the epilogue (the repo's VU dialect)

Instruction words: a scheduled cycle is one 64-bit upper and one 64-bit lower word of
micro memory, i.e. two words; a loop body that runs straight-line is stored whole.

Run from the TyraX root:  python tools/vu1-skin-schedule.py [--program PATH --copies 2 --k 4]
"""
import argparse
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
CORE = ROOT / "vendor/tyra/engine/src/renderer/3d/pipeline/static/core/compact"
SKETCH = CORE / "skin_vu1_blend_sketch.vsm.txt"

UPPER_MNEMONICS = {"mula", "madda", "madd", "mul", "add", "itof0", "ftoi0", "rsqrt"}
LOWER_MNEMONICS = {"lq", "ilw", "sq"}
ACC = "acc"
JOINT_RE = re.compile(r"(?:_|jo)([0-3])\b")
REG_RE = re.compile(r"^([A-Za-z][A-Za-z0-9_]*)")
TOKEN_RE = re.compile(r"[A-Za-z][A-Za-z0-9_#]*")
# never renamed, never allocated: vone127 maps to vf31, q is the one Q register, vi00 is zero
CONSTANT_NAMES = {"vone127", "vi00", "q"}
USABLE_VF = 30
LATENCY = {"fmac": 4, "rsqrt": 12, "load": 4}

PROGRAM_HEAD = """; Skinning on VU1 - the blend pass, two corners per loop iteration.
; GENERATED by tools/vu1-skin-schedule.py --program from skin_vu1_blend_sketch.vsm.txt:
; do not edit by hand. Not linked into the engine (the .txt suffix keeps it out of the
; build); the assembled size and the cycle figures are in docs/animated-models.md.
;
; Batch buffer (qwords): 0 header (x = corner pairs in the batch), then per corner six
; qwords: 0 bind index (int16 x y z, w = 1), 1 ST, 2 colour, 3 bind normal (int8 x127),
; 4 joint offsets (pre-scaled palette qwords), 5 raw weights. The blend overwrites qwords
; 0 and 3 with the blended index and normal; the tail that follows reads them.
; qword 22 holds the constant 127 in x (written by the EE with the palette sides).

.syntax new
.name StaPipVU1SkinBlendPass
.vu
.init_vf_all
.init_vi_all

--enter
--endenter

#vuprog StaPipVU1SkinBlendPass

    lq         vf31, 22(vi00)         ; the renormalise numerator, x = 127
begin:
    xtop       vi13                   ; the batch buffer
    ilw.w      vi14, 0(vi13)          ; corner pairs in this batch
    iaddiu     vi1, vi13, 2           ; corner A: the first corner after the header
    iaddiu     vi2, vi13, 8           ; corner B: six qwords on
loop:
"""

PROGRAM_TAIL = """    iaddiu     vi1, vi1, 12           ; the next pair: two corners of six qwords
    iaddiu     vi2, vi2, 12
    iaddi      vi14, vi14, -1         ; the pair count
    ibne       vi14, vi00, loop

--barrier
--cont

    b          begin

#endvuprog

--exit
--endexit
"""


def latency(mnemonic):
    if mnemonic == "rsqrt":
        return LATENCY["rsqrt"]
    if mnemonic in LOWER_MNEMONICS:
        return LATENCY["load"]
    return LATENCY["fmac"]


def base(operand):
    """A register name without its lane suffix, or None for an immediate / offset."""
    text = operand.strip()
    if "(" in text:  # offset(base)
        text = text[text.index("(") + 1:text.rindex(")")]
    m = REG_RE.match(text)
    return m.group(1) if m else None


def parse(path):
    """Operations of the body in program order (names not yet renamed)."""
    ops = []
    in_body = False
    for raw in path.read_text(encoding="utf-8").splitlines():
        stripped = raw.split(";", 1)[0].strip()
        if stripped.startswith("cornerLoop:"):
            in_body = True
            continue
        if not in_body or not stripped:
            continue
        if stripped.startswith("--barrier") or stripped.startswith("#endvuprog"):
            break
        parts = stripped.split(None, 1)
        mnemonic = parts[0].split(".")[0]
        if mnemonic not in LOWER_MNEMONICS and mnemonic not in UPPER_MNEMONICS:
            continue  # a directive, or an operation the blend does not use
        unit = "L" if mnemonic in LOWER_MNEMONICS else "U"
        operands = [o.strip() for o in parts[1].split(",")] if len(parts) > 1 else []
        if mnemonic == "sq":  # a store reads its first operand
            dst = None
            srcs = [base(operands[0]), base(operands[1])]
        elif mnemonic in LOWER_MNEMONICS:
            dst = base(operands[0])
            srcs = [base(operands[1])]
        else:
            dst = base(operands[0])
            srcs = [base(o) for o in operands[1:]]
        srcs = [s for s in srcs if s]
        if mnemonic in ("madda", "madd"):
            srcs.append(ACC)  # the accumulator is an implicit source
        if mnemonic in ("mula", "madda"):
            dst = ACC  # mula and madda write the accumulator
        joints = [int(j) for j in JOINT_RE.findall(stripped)]
        ops.append({"mn": mnemonic, "dst": dst, "srcs": srcs, "unit": unit,
                    "joint": max(joints) if joints else None,
                    "line": stripped, "lat": latency(mnemonic)})
    return ops


def variant(ops, k):
    """Keep the shared operations and the joint blocks below k."""
    return [op for op in ops if op["joint"] is None or op["joint"] < k]


def rename(ops, copy):
    """One corner copy: its own register names; constants and the Q register are shared."""
    out = []
    for op in ops:
        def r(name):
            if name is None or name in CONSTANT_NAMES:
                return name
            if name == ACC:
                return f"acc#{copy}"
            return f"{name}#{copy}"

        def sub(m):
            name = m.group(0)
            if name in CONSTANT_NAMES or name == ACC or name in ("x", "y", "z", "w"):
                return name
            if name.startswith("vi") and name[2:].isdigit():
                return name
            return f"{name}#{copy}"
        mnemonic, _, operands = op["line"].partition(" ")
        text = mnemonic
        if operands.strip():
            text += " " + TOKEN_RE.sub(sub, operands.strip())
        out.append({**op, "dst": r(op["dst"]), "srcs": [r(s) for s in op["srcs"]],
                    "copy": copy, "text": text})
    return out


def is_vf_value(name):
    return bool(name) and not name.startswith("acc#") and name != ACC and \
        not name.split("#")[0].startswith(("jo", "vc")) and name not in CONSTANT_NAMES


def dependencies(ops):
    """Program-order dependencies: (earlier op, minimum issue distance) per op."""
    deps = []
    for i, op in enumerate(ops):
        d = []
        for j in range(i):
            prev = ops[j]
            if prev["dst"] and prev["dst"] in op["srcs"]:
                d.append((j, prev["lat"]))                  # read after write
            if op["dst"] and op["dst"] in prev["srcs"]:
                d.append((j, 0))                            # write after read
            if op["dst"] and prev["dst"] == op["dst"]:
                d.append((j, prev["lat"] - op["lat"] + 1))  # write after write
        deps.append(d)
    return deps


def schedule(ops, in_order=False, vf_budget=None):
    """List schedule honouring every dependency; program order is the priority.
    Returns (cycles, issue times)."""
    deps = dependencies(ops)
    readers = {}
    for op in ops:
        for s_ in op["srcs"]:
            readers[s_] = readers.get(s_, 0) + 1
    remaining = dict(readers)
    live = set()
    t_issue = [None] * len(ops)
    unit_busy = set()
    pending = list(range(len(ops)))
    cycle = 0
    while pending:
        for idx in list(pending):
            op = ops[idx]
            if in_order and idx != pending[0]:
                break
            if any(t_issue[j] is None for j, _ in deps[idx]):
                continue
            earliest = max([t_issue[j] + dist for j, dist in deps[idx]] + [0])
            if earliest > cycle or (cycle, op["unit"]) in unit_busy:
                continue
            if vf_budget is not None and op["dst"] and is_vf_value(op["dst"]):
                freed = sum(1 for s_ in set(op["srcs"])
                            if s_ in live and remaining.get(s_, 0) == op["srcs"].count(s_))
                if len(live) - freed >= vf_budget:
                    continue
            unit_busy.add((cycle, op["unit"]))
            t_issue[idx] = cycle
            for s_ in op["srcs"]:
                remaining[s_] = remaining.get(s_, 0) - 1
                if remaining[s_] <= 0:
                    live.discard(s_)
            if op["dst"] and is_vf_value(op["dst"]) and readers.get(op["dst"], 0) > 0:
                live.add(op["dst"])
            pending.remove(idx)
        cycle += 1
        if cycle > 100000:
            raise RuntimeError("schedule did not converge")
    return (max(t_issue) + 1 if ops else 0), t_issue


def live_ranges(seq, times):
    """First definition and last use of each value (accumulator and constants excluded)."""
    first, last = {}, {}
    for op, t in zip(seq, times):
        d = op["dst"]
        if d and not d.startswith("acc#") and d not in CONSTANT_NAMES:
            first.setdefault(d, t)
        for s_ in op["srcs"]:
            if s_ and not s_.startswith("acc#") and s_ not in CONSTANT_NAMES:
                last[s_] = max(last.get(s_, -1), t)
    return {n: (first[n], last.get(n, first[n])) for n in first}


def peak_live(seq, times):
    """Peak simultaneously live VF and VI values in a schedule."""
    vf, vi = [], []
    for name, (s, e) in live_ranges(seq, times).items():
        (vi if name.split("#")[0].startswith(("jo", "vc")) else vf).append((s, e))

    def peak(intervals):
        return max((sum(1 for s, e in intervals if s <= c <= e)
                    for c in range(0, max([e for _, e in intervals] + [0]) + 1)), default=0)
    return peak(vf), peak(vi)


def allocate(seq, times, vf_pool, vi_pool, fixed):
    """Linear-scan register allocation over the live ranges. A register is free once its
    value's last reader has issued (a same-cycle reuse is safe: a write lands after its
    latency). Returns {name: register}; raises when a pool runs out."""
    ranges = live_ranges(seq, times)
    mapping = dict(fixed)
    free = {"vf": list(vf_pool), "vi": list(vi_pool)}
    busy = []  # (last use, name, register, kind)
    for name, (start, end) in sorted(ranges.items(), key=lambda kv: kv[1][0]):
        if name in mapping:
            continue
        for entry in list(busy):
            if entry[0] <= start:
                busy.remove(entry)
                free[entry[3]].append(entry[2])
        kind = "vi" if name.split("#")[0].startswith(("jo", "vc")) else "vf"
        if not free[kind]:
            raise RuntimeError(f"register allocation failed: no free {kind} for {name} at cycle {start}")
        reg = free[kind].pop(0)
        mapping[name] = reg
        busy.append((end, name, reg, kind))
    return mapping


def body_lines(seq, times, mapping):
    """Assembler lines in cycle order, one comment per schedule cycle."""
    by_cycle = {}
    for op, t in zip(seq, times):
        by_cycle.setdefault(t, []).append(op)
    lines = []
    for t in sorted(by_cycle):
        lines.append(f"    ; cycle {t}")
        for op in sorted(by_cycle[t], key=lambda o: o["unit"]):
            lines.append("    " + TOKEN_RE.sub(lambda m: mapping.get(m.group(0), m.group(0)), op["text"]))
    return lines, len(by_cycle)


def build(ops, k, copies):
    """The scheduled, register-allocated body of `copies` corners."""
    body = variant(ops, k)
    seq = []
    for copy in range(copies):
        seq += rename(body, copy)
    cycles, times = schedule(seq, vf_budget=USABLE_VF)
    fixed = {"vone127": "vf31"}
    for copy in range(copies):
        fixed[f"vc#{copy}"] = f"vi{1 + copy}"
    vf_pool = [f"vf{r}" for r in range(1, 31)]
    vi_pool = [f"vi{r}" for r in range(3, 13)]
    mapping = allocate(seq, times, vf_pool, vi_pool, fixed)
    return seq, times, cycles, mapping


def main():
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--sketch", default=str(SKETCH))
    parser.add_argument("--load-latency", type=int, default=4)
    parser.add_argument("--fmac-latency", type=int, default=4)
    parser.add_argument("--rsqrt-latency", type=int, default=12)
    parser.add_argument("--emit", default=None, help="write the scheduled body as assembler lines")
    parser.add_argument("--program", default=None, help="write the whole pass as .vclpp source")
    parser.add_argument("--copies", type=int, default=2)
    parser.add_argument("--k", type=int, default=4)
    args = parser.parse_args()
    LATENCY["load"] = args.load_latency
    LATENCY["fmac"] = args.fmac_latency
    LATENCY["rsqrt"] = args.rsqrt_latency
    ops = parse(Path(args.sketch))
    if not ops:
        print("no blend instructions found after the cornerLoop label", file=sys.stderr)
        return 1
    if args.emit or args.program:
        seq, times, cycles, mapping = build(ops, args.k, args.copies)
        lines, count = body_lines(seq, times, mapping)
        vf, vi = peak_live(seq, times)
        if args.emit:
            Path(args.emit).write_text("\n".join(lines) + "\n", encoding="utf-8", newline="\n")
        if args.program:
            Path(args.program).write_text(PROGRAM_HEAD + "\n".join(lines) + "\n" + PROGRAM_TAIL,
                                          encoding="utf-8", newline="\n")
        print(f"scheduled {args.copies} corners, k={args.k}: {cycles} cycles "
              f"({cycles / args.copies:.1f} a corner), {count} issue cycles, peak VF {vf}, VI {vi}")
        return 0
    print(f"sketch: {args.sketch}")
    print(f"latencies: FMAC/ITOF {LATENCY['fmac']}, RSQRT {LATENCY['rsqrt']}, LQ/ILW {LATENCY['load']} cycles")
    print(f"{'k':>2} {'upper':>6} {'lower':>6} {'isolated':>9} {'in-order':>9} {'steady1':>8} "
          f"{'steady2':>8} {'steady3':>8} {'VF pk2':>7} {'VF pk3':>7} {'VI pk3':>7} {'words3':>7}")
    for k in (1, 2, 3, 4):
        body = variant(ops, k)
        upper = sum(1 for o in body if o["unit"] == "U")
        lower = sum(1 for o in body if o["unit"] == "L")
        iso_cycles, _ = schedule(rename(body, 0), vf_budget=USABLE_VF)
        in_order_cycles, _ = schedule(rename(body, 0), in_order=True)
        per = {}
        for copies in (1, 2, 3):
            seq = []
            for copy in range(copies):
                seq += rename(body, copy)
            cycles, times = schedule(seq, vf_budget=USABLE_VF)
            vf, vi = peak_live(seq, times)
            per[copies] = (cycles / copies, vf, vi, cycles)
        print(f"{k:>2} {upper:>6} {lower:>6} {iso_cycles:>9} {in_order_cycles:>9} {per[1][0]:>8.1f} "
              f"{per[2][0]:>8.1f} {per[3][0]:>8.1f} {per[2][1]:>7} {per[3][1]:>7} {per[3][2]:>7} "
              f"{2 * per[3][3]:>7}")
    print("steadyN: N corners of one body list-scheduled together, cycles per corner; VF pkN: peak")
    print("live VF values (budget 30); words3: 2 x the three-corner body's cycles.")
    return 0


if __name__ == "__main__":
    sys.exit(main())
